const express = require('express');
const router = express.Router();
const pool = require('../db');

router.get('/', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM communications ORDER BY sent_at DESC');
    res.json(result.rows);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.get('/:id', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM communications WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.post('/', async (req, res) => {
  try {
    const { sender, recipient, channel, subject, message, priority, status } = req.body;
    const result = await pool.query(
      `INSERT INTO communications (sender, recipient, channel, subject, message, priority, status)
       VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *`,
      [sender, recipient, channel || 'radio', subject, message, priority || 'normal', status || 'sent']
    );
    res.status(201).json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.put('/:id', async (req, res) => {
  try {
    const { sender, recipient, channel, subject, message, priority, status } = req.body;
    const result = await pool.query(
      `UPDATE communications SET sender=$1, recipient=$2, channel=$3, subject=$4, message=$5, priority=$6, status=$7, updated_at=NOW()
       WHERE id=$8 RETURNING *`,
      [sender, recipient, channel, subject, message, priority, status, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.delete('/:id', async (req, res) => {
  try {
    const result = await pool.query('DELETE FROM communications WHERE id=$1 RETURNING *', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json({ message: 'Deleted successfully' });
  } catch (err) { res.status(500).json({ error: err.message }); }
});

module.exports = router;
